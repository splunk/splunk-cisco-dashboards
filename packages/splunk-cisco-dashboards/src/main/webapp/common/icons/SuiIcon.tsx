export interface SuiIconProps extends React.SVGProps<SVGSVGElement> {
    absoluteStrokeWidth?: boolean;
    size?: string | number;
    strokeWidth?: string | number;
    variant?: 'default' | 'outlined' | 'filled';
}

export type SuiIcon = React.ForwardRefExoticComponent<
    SuiIconProps & React.RefAttributes<SVGSVGElement>
>;

const adaptSuiIcon = (Icon: React.ElementType, displayName: string): SuiIcon => {
    const WrappedIcon = React.forwardRef<SVGSVGElement, SuiIconProps>(
        (
            {
                size = 16,
                width = size,
                height = size,
                strokeWidth: _strokeWidth,
                absoluteStrokeWidth: _absoluteStrokeWidth,
                ...otherProps
            },
            _ref
        ) => <Icon width={width} height={height} {...otherProps} />
    );

    WrappedIcon.displayName = displayName;
    return WrappedIcon;
};

